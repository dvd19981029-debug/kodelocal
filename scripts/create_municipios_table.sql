-- Fuente: BD KODE.xlsx (Hoja: Municipios)
-- id_municipio: Código enviado a C807 Express al generar la Guía
-- nombre_municipio: Lo que ven los asesores cuando registran el pedido
-- id_depto: Relación con la tabla departamentos (2 al 15)
-- municipio_mh: Código enviado a Factura Llama / Ministerio de Hacienda
-- nombre_mh: Nuevo nombre de acuerdo a la reestructuración municipal del país

CREATE TABLE IF NOT EXISTS public.municipios (
    id_municipio INT PRIMARY KEY,
    nombre_municipio VARCHAR(100) NOT NULL,
    id_depto INT NOT NULL REFERENCES public.departamentos(id),
    municipio_mh VARCHAR(10) NOT NULL,
    nombre_mh VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_municipios_id_depto ON public.municipios(id_depto);
CREATE INDEX IF NOT EXISTS idx_municipios_nombre ON public.municipios(nombre_municipio);
CREATE INDEX IF NOT EXISTS idx_municipios_mh ON public.municipios(municipio_mh);

