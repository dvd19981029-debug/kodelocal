export interface ProductItem {
  id: string;
  sku: string;
  barcode: string;
  name: string;
  officialName?: string; // Nombre comercial oficial (ej. Hombre Salvaje)
  brand?: string;
  gender?: string; // Caballero, Dama, Unisex
  category: string;
  unit: string; // Onza, Unidad, Paquete, Galón
  price: number; // Precio por Onza (o precio base por unidad)
  priceHalfOunce?: number; // Precio Media Onza (mostrado en ecommerce)
  finishedPerfumePrice?: number; // Precio Perfume Terminado 100ml ("Arma tu propio perfume")
  cost: number;
  stock: number;
  stockHalf?: number; // Frascos de media onza envasados (stock = frascos de 1 onza)
  minStock: number;
  imageUrl: string;
  description?: string;
  isAvailableOnline: boolean;
  puesto?: string; // Ubicación física en estante (Ej: A1 = Estante A, Nivel 1)
  supplier?: string; // Proveedor
}

export interface CartItem {
  product: ProductItem;
  quantity: number;
  presentation?: 'ONZA_COMPLETA' | 'MEDIA_ONZA' | 'UNIDAD';
}

